-- BU KURUM TABLOSU
CREATE TABLE Institution(
	InstitutionID INT IDENTITY(1,1) PRIMARY KEY,
	Name NVARCHAR(150) NOT NULL,
	Type NVARCHAR(50) NOT NULL,
	City NVARCHAR(50),
	CreateAt DATETIME DEFAULT GETDATE()
);

--KULLANICILAR TABLOSU
CREATE TABLE Users(
	UserID INT IDENTITY(1,1) PRIMARY KEY,
	InstitutionID INT FOREIGN KEY REFERENCES Institution(InstitutionID),
	FullName NVARCHAR(100) NOT NULL,
	Email NVARCHAR(100) UNIQUE NOT NULL,
	PasswordHash NVARCHAR(255) NOT NULL,
	Phone NVARCHAR(20) NOT NULL,
	IsActive BIT DEFAULT 1,
	CreatedAt DATETIME DEFAULT GETDATE()
);

--YETKİ SINIFI
CREATE TABLE Roles(
	RoleID INT IDENTITY(1,1) PRIMARY KEY,
	RoleName NVARCHAR(50) NOT NULL
);

--KULLANICI ROL EŞLEŞMESİ TABLOSU
CREATE TABLE User_Roles(
	UserId INT FOREIGN KEY REFERENCES Users(UserID) ON DELETE CASCADE,
	RoleID INT FOREIGN KEY REFERENCES Roles(RoleID)  ON DELETE CASCADE,
	PRIMARY KEY(UserID,RoleID)
);

--BİREY PROFİLİ
CREATE TABLE Individuals(
	IndividualID INT IDENTITY(1,1) PRIMARY KEY,
	FullName NVARCHAR(100) NOT NULL,
	TCIdentitiyNumber NVARCHAR(11) NOT NULL UNIQUE,
	BırtDate DATE,
	Gender NVARCHAR(10),
	Address NVARCHAR(255),
	CreatedAt DATETIME DEFAULT GETDATE()
);

--TANI ENGEL KISMI
CREATE TABLE Diagnosis_Profiles(
	DiagnosisID INT IDENTITY(1,1) PRIMARY KEY,
	IndividualID INT FOREIGN KEY REFERENCES Individuals(IndividualID) ON DELETE CASCADE,
	ICDCode NVARCHAR(20) NOT NULL, -- ATIYORUM BU KLISIM OTİZİM KOD FD40 GİBİ
	DiagnosisName NVARCHAR(150) NOT NULL,
	SeverityLevel NVARCHAR(50),
	DiagnosedDate DATE
);

--GEREKSİNİM TÜRÜ TABLOSU 
CREATE TABLE Disability_Types(
	DisabilityTypeID INT IDENTITY(1,1) PRIMARY KEY,
	TypeName NVARCHAR(100) NOT NULL,
	Description NVARCHAR(255)
);

--Doktor veli eşleme tablosu
CREATE TABLE Care_Team(
	AssignmentID INT IDENTITY(1,1) PRIMARY KEY,
	IndividualID INT FOREIGN KEY REFERENCES Individuals(IndividualID) ON DELETE CASCADE,
	UserID INT FOREIGN KEY REFERENCES Users(UserID) ON DELETE CASCADE,
	RelationType NVARCHAR(50) NOT NULL
);

--KRİZ KISMI
CREATE TABLE Incident_Types(
	TypeID INT IDENTITY(1,1) PRIMARY KEY,
	DisabilityTypeID INT FOREIGN KEY REFERENCES Disability_Types(DisabilityTypeID),
	TypeName NVARCHAR(100) NOT NULL,
	Description NVARCHAR(255)
);

--AİLENİN GİRİDĞİ OLAY KISMI
CREATE TABLE Incident_Logs(
	IncidentID INT IDENTITY(1,1) PRIMARY KEY,
	IndividualID INT FOREIGN KEY REFERENCES Individuals(IndividualID),
	TypeID INT FOREIGN KEY REFERENCES Incident_Types(TypeID),
	LoggedByUserID INT FOREIGN KEY REFERENCES Users(UserID),
	SeverityScore INT,
	Triggers NVARCHAR(255),
	Description NVARCHAR(MAX),
	IncidentDate DATETIME DEFAULT GETDATE()
);
